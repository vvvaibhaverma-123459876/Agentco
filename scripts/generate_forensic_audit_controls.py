#!/usr/bin/env python3
"""Generate forensic audit control ledgers.

The output is intentionally conservative. It separates inventory coverage from
line-level audit completion and prevents a future report from calling the audit
complete without explicit accounting for requirements, integrations, claims, and
external dependencies.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_JSON = ROOT / "docs" / "audit" / "FORENSIC_AUDIT_CONTROLS.json"
OUT_MD = ROOT / "docs" / "audit" / "FORENSIC_AUDIT_CONTROLS.md"

PURPOSE = (
    "AgentCo exists to evolve into progressively more general intelligence by "
    "operating as an evidence-governed, calibration-driven AI civilization "
    "that learns continuously, improves itself safely, and expands its "
    "capability across domains over time."
)


def run(args: list[str]) -> str:
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def git_files() -> list[str]:
    return [line for line in run(["git", "ls-files"]).splitlines() if line]


def exists(path: str) -> bool:
    return (ROOT / path).exists()


def text_contains(path: str, needle: str) -> bool:
    candidate = ROOT / path
    return candidate.exists() and needle in candidate.read_text(encoding="utf-8")


