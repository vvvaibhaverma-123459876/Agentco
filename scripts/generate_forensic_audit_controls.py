def main() -> int:
    files = git_files()
    tests = [p for p in files if p.startswith("tests/") or "/tests/" in p or Path(p).name.startswith("test_")]
    workflows = workflow_rows()
    claims = claim_rows()
    requirements = requirement_rows()
    dependencies = external_dependencies()

    completeness = {
        "total_files_discovered": len(files),
        "files_inventoried": len(files) if exists("docs/audit/FORENSIC_FILE_INVENTORY.json") else 0,
        "files_line_audited": 0,
        "files_excluded": 0,
        "file_audit_note": "All tracked files are inventoried. Line-level review is intentionally not marked complete by this generated control ledger.",
        "tests_discovered": len(tests),
        "workflows_discovered": len(workflows),
        "workflows_tested_or_gated": sum(1 for w in workflows if w["test_evidence"]),
        "integrations_discovered": len(dependencies),
        "integrations_verified_without_external_dependency": sum(
            1 for d in dependencies if d["classification"] in {"verified", "optional_unavailable"}
        ),
        "claims_discovered": len(claims),
        "claims_proven_or_limited": sum(
            1 for c in claims if c["classification"] in {"verified_static_and_smoke", "verified_with_limitations", "verified_when_command_passes"}
        ),
        "requirements_discovered": len(requirements),
        "requirements_with_test_evidence": sum(1 for r in requirements if r["test_evidence"]),
    }

    post_remediation_reaudit = [
        {
            "check": "New regressions",
            "method": "Run release gate and focused contract tests after remediation.",
            "status": "required_before_final_verdict",
        },
        {
            "check": "Tests weakened during remediation",
            "method": "Review git diff for removed assertions, new skips, xfails, or force exits.",
            "status": "required_before_final_verdict",
        },
        {
            "check": "Documentation drift",
            "method": "Compare README/Helm/Makefile commands to actual targets and tests.",
            "status": "required_before_final_verdict",
        },
        {
            "check": "Temporary bridges and duplicated architecture",
            "method": "Search for TODO/FIXME/stub/mock/fallback and classify remaining hits.",
            "status": "required_before_final_verdict",
        },
        {
            "check": "Resolved finding accuracy",
            "method": "Re-run original reproduction checks and ensure new tests fail on the old behavior.",
            "status": "required_before_final_verdict",
        },
    ]

    payload = {
        "generated_by": "scripts/generate_forensic_audit_controls.py",
        "repository_purpose": PURPOSE,
        "requirements_to_behaviour_matrix": requirements,
        "external_dependency_audit": dependencies,
        "workflow_coverage": workflows,
        "claim_to_evidence_matrix": claims,
        "finding_completeness_ledger": completeness,
        "independent_post_remediation_reaudit": post_remediation_reaudit,
    }
    OUT_JSON.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    lines = [
        "# Forensic Audit Controls",
        "",
        f"Repository purpose: {PURPOSE}",
        "",
        "## Requirements-To-Behaviour Matrix",
        "",
        "| ID | Capability | Who needs it | Trigger | Input/output | Success criteria | Failure expectations | Workflow | Test evidence | Production evidence | Status |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in requirements:
        lines.append(
            "| {id} | {capability} | {who_needs_it} | {trigger} | {input_output} | {success_criteria} | {failure_expectations} | {implementing_workflow} | {test_evidence} | {production_evidence} | {status} |".format(
                **row
            )
        )
    lines.extend([
        "",
        "## Cross-Repository And External Dependency Audit",
        "",
        "| Name | Type | Consumer | Configuration | Classification | Evidence |",
        "|---|---|---|---|---|---|",
    ])
    for dep in dependencies:
        lines.append(
            f"| {dep['name']} | {dep['type']} | {dep['consumer']} | {dep['configuration']} | {dep['classification']} | {dep['evidence']} |"
        )
    lines.extend([
        "",
        "## Finding Completeness Ledger",
        "",
        "| Metric | Value |",
        "|---|---:|",
    ])
    for key, value in completeness.items():
        lines.append(f"| {key} | {value} |")
    lines.extend([
        "",
        "## Initial Claim-To-Evidence Matrix",
        "",
        "| Claim | Implementation evidence | Runtime entrypoint | Classification | Limitation |",
        "|---|---|---|---|---|",
    ])
    for claim in claims:
        lines.append(
            f"| {claim['claim']} | {claim['implementation_evidence']} | {claim['runtime_entrypoint']} | {claim['classification']} | {claim['limitation']} |"
        )
    lines.extend([
        "",
        "## Independent Post-Remediation Re-Audit Checklist",
        "",
        "| Check | Method | Status |",
        "|---|---|---|",
    ])
    for item in post_remediation_reaudit:
        lines.append(f"| {item['check']} | {item['method']} | {item['status']} |")
    OUT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
